/*
 * The route contract of the generated documentation pages.
 *
 * These four assertions are the ones that fail loudly when the registry and the
 * file system disagree: a generated entry whose URL a static directory has taken
 * over, a generated entry documented at somebody else's URL, a route two entries
 * claim at once, and an entry that belongs to no family (which would make it
 * invisible to the API index).
 *
 * They read the real registry and the real `app/` tree, so they cannot pass by
 * agreeing with a copy of either.
 */

import { existsSync, readdirSync } from "node:fs";
import path from "node:path";
import { describe, expect, it } from "vitest";
import { docEntries, docFamilies, entriesInFamily } from "@/lib/docs/registry";

/*
 * The App Router tree, found from the working directory rather than from
 * `import.meta.url`: these tests run in the library's jsdom environment, where
 * `import.meta.url` is not a file URL. Both plausible roots are tried so the
 * file works whether Vitest is invoked from the Showcase or from the package.
 */
const appRoot = [
  "app",
  "apps/showcase/app",
  "../../apps/showcase/app",
].map((relative) => path.resolve(process.cwd(), relative))
  .find((candidate) => existsSync(path.join(candidate, "components")));

if (!appRoot) {
  throw new Error(
    `doc-pages-routes: could not locate the Showcase app directory from ${process.cwd()}`,
  );
}

/** A static directory under `app/<group>/` wins over the dynamic route. */
function staticSlugs(group: string): string[] {
  const dir = path.join(appRoot, group);
  if (!existsSync(dir)) return [];
  return readdirSync(dir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && !entry.name.startsWith("["))
    .map((entry) => entry.name);
}

/** The groups whose pages are generated by a `[slug]` route. */
const GENERATED_GROUPS = ["components", "charts", "motion"] as const;

function isGeneratedGroup(group: string): boolean {
  return (GENERATED_GROUPS as readonly string[]).includes(group);
}

const generated = docEntries.filter((entry) => entry.status === "generated");

describe("generated documentation routes", () => {
  it("generates a page at the entry's own URL for every generated entry", () => {
    const wrong = generated
      .filter((entry) => isGeneratedGroup(entry.group))
      .filter((entry) => entry.route !== `/${entry.group}/${entry.id}`);
    expect(wrong.map((entry) => `${entry.id} -> ${entry.route}`)).toEqual([]);
  });

  it("never generates over a hand-written static directory", () => {
    const collisions = generated.flatMap((entry) => {
      if (!isGeneratedGroup(entry.group)) return [];
      return staticSlugs(entry.group).includes(entry.id) ? [`${entry.group}/${entry.id}`] : [];
    });
    expect(collisions).toEqual([]);
  });

  it("gives a generated entry a unique route", () => {
    const routes = generated.map((entry) => entry.route);
    const duplicated = routes.filter((route, index) => routes.indexOf(route) !== index);
    expect([...new Set(duplicated)]).toEqual([]);
  });

  it("documents every non-reference entry on exactly one family page", () => {
    const listed = new Set(
      docFamilies.flatMap((family) => entriesInFamily(family.id).map((entry) => entry.id)),
    );
    const missing = docEntries
      .filter((entry) => entry.status !== "reference")
      .filter((entry) => !listed.has(entry.id))
      .map((entry) => entry.id);
    expect(missing).toEqual([]);
  });
});
